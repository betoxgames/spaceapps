import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:720}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
const view=()=>page.evaluate(()=>window.__SPACE_PAPERS__.view());
const state=()=>page.evaluate(()=>window.__SPACE_PAPERS__.state());
try {
  await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:4173/');
  await page.locator('[data-action="new-shift"]').click();
  assert.equal((await view()).camera,'room');
  assert.equal(await page.locator('#objects').evaluate(e=>e.inert),true);
  assert.equal(await page.locator('#flight').isVisible(),false);
  assert.equal(await page.locator('[data-stamp-tool="approve"]').isVisible(),false);
  mkdirSync('test-results',{recursive:true});
  await page.screenshot({path:'test-results/camera-room.png'});
  for(let i=0;i<3;i++){await page.keyboard.press('Tab');assert.equal(await page.evaluate(()=>!!document.activeElement?.closest('.desk-tools, .desk-rail, #objects')),false,'hidden desk controls must not receive focus');}
  // Tabbing beyond page controls may move focus to browser chrome and pause the game.
  if ((await view()).paused) await page.locator('[data-action="resume"]').click();
  const initial=await state();
  await page.getByRole('button',{name:/Inspect desk/}).click();
  assert.equal((await view()).camera,'desk');
  assert.equal(await page.locator('#objects').evaluate(e=>e.inert),false);
  await page.keyboard.press('b');
  assert.equal(await page.locator('#manual').isVisible(),true);
  await page.locator('[data-action="book-destinations"]').first().click();
  await page.locator('[data-action="destination-earth"]').click();
  assert.equal((await view()).bookDestination,'earth');
  await page.locator('#flight').focus();
  await page.keyboard.press('Enter');await page.keyboard.press('ArrowLeft');await page.keyboard.press('Enter');
  const position=await page.locator('#flight').evaluate(e=>e.style.transform);
  await page.screenshot({path:'test-results/camera-desk.png'});
  await page.getByRole('button',{name:'Room view'}).click();
  assert.equal((await view()).camera,'room');
  assert.equal(await page.locator('#objects').evaluate(e=>e.inert),true);
  assert.equal(await page.locator('#flight').isVisible(),false);
  assert.equal(await page.locator('#flight').evaluate(e=>{e.focus();return document.activeElement===e;}),false);
  await page.getByRole('button',{name:'Desk view'}).click();
  assert.equal(await page.locator('#flight').evaluate(e=>e.style.transform),position);
  assert.equal(await page.locator('#flight').evaluate(e=>document.activeElement===e),true,'returning to desk restores the focused document');
  assert.equal((await view()).bookDestination,'earth');
  assert.equal(await page.locator('#manual').isVisible(),true);
  assert.deepEqual(await state(),initial,'camera and document inspection must not change campaign accounting');
  await page.getByRole('button',{name:'Room view'}).click();
  await page.keyboard.press('b');
  assert.equal((await view()).camera,'desk','B opens the manual from the room');
  assert.equal(await page.locator('#manual').isVisible(),true);
  await page.evaluate(()=>window.__SPACE_PAPERS__.scenario('emergency:E02'));
  assert.equal((await view()).camera,'desk');
  assert.equal(await page.getByRole('button',{name:'Room view'}).isDisabled(),true);
  await page.keyboard.press('Escape');const time=(await view()).remaining;
  const frame=await page.locator('.scene-door').evaluate(e=>e.style.getPropertyValue('--door-frame'));
  await page.waitForTimeout(300);assert.equal((await view()).remaining,time,'pause freezes emergency clock');
  assert.equal(await page.locator('.scene-door').evaluate(e=>e.style.getPropertyValue('--door-frame')),frame,'pause freezes door animation');
  await page.locator('[data-action="resume"]').click();
  assert.equal(await page.getByRole('button',{name:'Room view'}).isDisabled(),true);
  assert.deepEqual(errors,[]);
  console.log('PASS: room and desk camera, inspection, document and manual persistence, campaign accounting, inert room objects, emergency and pause, no page errors.');
} finally {await browser.close();}
