import { build } from 'vite';
import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const publicDir = path.join(root, 'public');
const result = await build({
  configFile: false, root, publicDir, base: './',
  define: { 'import.meta.env.DEV': 'false', 'import.meta.env.BASE_URL': JSON.stringify('./') },
  build: {
    write: false, copyPublicDir: false, target: 'es2022',
    lib: { entry: path.join(root, 'src/main.ts'), name: 'SpacePapers', formats: ['iife'] },
    minify: 'esbuild', cssMinify: true,
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});
const output = Array.isArray(result) ? result[0].output : result.output;
const js = output.filter(file => file.type === 'chunk').map(file => file.code).join('\n');
// CSS is located in runtime/, so references must be relative to that directory.
let css = output.filter(file => file.type === 'asset' && file.fileName.endsWith('.css')).map(file => String(file.source)).join('\n');
css = css.replace(/url\((['"]?)((?:\.\.?\/|\/)?assets\/[^)'"\s]+)\1\)/g, (_, quote, url) => `url(${quote}../public/${url.replace(/^(?:\.\.?\/|\/)/, '')}${quote})`);

// Fetching local files from file:// is blocked by browsers. Keep the
// Web Audio recordings as data URLs. The GLB uses a separate lazy classic script.
const audio = {};
for (const name of ['ambient-music.mp3', 'door.mp3', 'stamp.mp3', 'ship-engine.mp3']) {
  const key = `assets/audio/${name}`;
  audio[key] = `data:audio/mpeg;base64,${(await readFile(path.join(publicDir, key))).toString('base64')}`;
}
const audioJs = `window.__SPACE_PAPERS_ASSETS__=${JSON.stringify(audio)};\n`;
const hashed = (stem, extension, contents) => `${stem}-${createHash('sha256').update(contents).digest('hex').slice(0, 12)}.${extension}`;
const moonJs = `window.__SPACE_PAPERS_MOON__=${JSON.stringify((await readFile(path.join(publicDir,'assets/models/moon-menu.glb'))).toString('base64'))};\n`;
const moonFile = hashed('moon-data', 'js', moonJs);
const files = {
  [hashed('app', 'js', js)]: js,
  [hashed('style', 'css', css)]: css,
  [hashed('audio-data', 'js', audioJs)]: audioJs,
  [moonFile]: moonJs,
};
const [app, style, audioFile] = Object.keys(files);
const html = `<!doctype html>\n<!-- Generated by pnpm build. Edit src/ and public/, then rebuild. -->\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#06080b"><title>Space Papers · Lunar Operations</title><link rel="stylesheet" href="runtime/${style}"></head><body><div id="app"></div><noscript>Enable JavaScript to play Space Papers.</noscript><script src="runtime/${audioFile}"></script><script>window.__SPACE_PAPERS_MOON_SCRIPT__="runtime/${moonFile}";</script><script src="runtime/${app}"></script></body></html>\n`;

async function atomicWrite(file, contents) {
  const temporary = `${file}.${process.pid}.tmp`;
  try { await writeFile(temporary, contents); await rename(temporary, file); }
  finally { await rm(temporary, { force: true }); }
}
async function writeRuntime(destination) {
  const runtime = path.join(destination, 'runtime');
  await mkdir(runtime, { recursive: true });
  await Promise.all(Object.entries(files).map(([name, contents]) => atomicWrite(path.join(runtime, name), contents)));
  await atomicWrite(path.join(destination, 'index.html'), html);
  // Only generated files with our exact naming pattern are managed here.
  for (const file of await readdir(runtime)) {
    if (/^(?:app-[a-f0-9]{12}\.js|style-[a-f0-9]{12}\.css|audio-data-[a-f0-9]{12}\.js|moon-data-[a-f0-9]{12}\.js)$/.test(file) && !(file in files)) {
      await rm(path.join(runtime, file));
    }
  }
}
await writeRuntime(root);
const dist = path.join(root, 'dist');
// dist/ is disposable build output, including artifacts from older layouts.
await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
await cp(publicDir, path.join(dist, 'public'), { recursive: true, force: true });
await writeRuntime(dist);
console.log('Offline build: index.html + runtime/ + public/; complete copy in dist/. Open index.html directly.');
