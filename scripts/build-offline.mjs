import { build } from 'vite';
import { readFile,writeFile,mkdir,readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const assets={};
const mime={'.webp':'image/webp','.png':'image/png','.jpg':'image/jpeg','.jpeg':'image/jpeg','.woff2':'font/woff2','.ttf':'font/ttf'};
async function collect(directory){
 for(const e of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name,'en'))){
  const file=path.join(directory,e.name);
  if(e.isDirectory()){await collect(file);continue;}
  if(!mime[path.extname(file)]||e.name==='combined-reference.webp')continue;
  assets[path.relative(path.join(root,'public'),file).split(path.sep).join('/')]=`data:${mime[path.extname(file)]};base64,${(await readFile(file)).toString('base64')}`;
 }
}
await collect(path.join(root,'public'));
const result=await build({configFile:false,root,publicDir:false,base:'./',define:{'import.meta.env.DEV':'false','import.meta.env.BASE_URL':JSON.stringify('./')},build:{write:false,target:'es2022',lib:{entry:path.join(root,'src/main.ts'),name:'SpacePapers',formats:['iife']},minify:'esbuild',cssMinify:true,rollupOptions:{output:{inlineDynamicImports:true}}}});
const output=Array.isArray(result)?result[0].output:result.output;
const js=output.filter(f=>f.type==='chunk').map(f=>f.code).join('\n');
let css=output.filter(f=>f.type==='asset'&&f.fileName.endsWith('.css')).map(f=>String(f.source)).join('\n');
css=css.replace(/url\((['"]?)([^)'"\s]+)\1\)/g,(match,_quote,url)=>{
 const key=url.replace(/^\.\//,'').replace(/^\//,'');return assets[key]?`url("${assets[key]}")`:match;
});
if(css.match(/url\((['"]?)(?!data:)[^)]*\/art\//))throw Error('Unembedded CSS art');
const html=`<!doctype html>\n<!-- Generated by pnpm build. Edit dev.html and src/, then rebuild. -->\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#08232c"><title>Space Papers · Lunar Operations</title><style>${css.replaceAll('</style','<\\/style')}</style></head><body><div id="app"></div><noscript>Enable JavaScript to play Space Papers.</noscript><script>window.__SPACE_PAPERS_ASSETS__=${JSON.stringify(assets)};</script><script>${js.replaceAll('</script','<\\/script')}</script></body></html>\n`;
await mkdir(path.join(root,'dist'),{recursive:true});
await writeFile(path.join(root,'index.html'),html);
await writeFile(path.join(root,'dist/index.html'),html);
console.log(`Offline build: index.html + dist/index.html (${(Buffer.byteLength(html)/1024/1024).toFixed(2)} MB), ${Object.keys(assets).length} embedded assets. Open directly; no installation or server required.`);
